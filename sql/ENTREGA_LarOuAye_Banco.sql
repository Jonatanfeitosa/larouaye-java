    CONSTRAINT CK_CONSULTA_ORIENTACAO CHECK ((CD_STATUS = 1 AND CD_ORIENTACAO IS NOT NULL) OR (CD_STATUS <> 1 AND CD_ORIENTACAO IS NULL)),
    CONSTRAINT CK_CONSULTA_PERGUNTA CHECK (LENGTH(TRIM(DS_PERGUNTA)) > 0)
);
COMMENT ON TABLE  TB_CONSULTA IS 'Histórico das perguntas, com a categoria prevista pelo ML, a confiança e a orientação entregue.';
COMMENT ON COLUMN TB_CONSULTA.VL_CONFIANCA IS 'Confiança do classificador (0 a 1). Informativa: quem decide é o Java.';
COMMENT ON COLUMN TB_CONSULTA.CD_ETAPA IS 'Etapa da compra em que o cidadão estava ao perguntar (FK para tb_etapa)';
COMMENT ON COLUMN TB_CONSULTA.CD_STATUS IS 'Resultado da consulta (FK para tb_status_consulta; 1 = RESPONDIDA exige orientação)';

