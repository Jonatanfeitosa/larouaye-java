    CONSTRAINT UK_CATEGORIA_CODIGO UNIQUE (CD_CODIGO),
    CONSTRAINT CK_CATEGORIA_CODIGO CHECK (CD_CODIGO = UPPER(CD_CODIGO) AND LENGTH(TRIM(CD_CODIGO)) > 0)
