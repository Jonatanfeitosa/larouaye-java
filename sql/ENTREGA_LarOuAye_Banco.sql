CREATE TABLE TB_CANAL (
    CD_CANAL   NUMBER(10)    NOT NULL,
    CD_CODIGO  VARCHAR2(10)  NOT NULL,
    NM_CANAL   VARCHAR2(40)  NOT NULL,
    CONSTRAINT PK_CANAL PRIMARY KEY (CD_CANAL),
    CONSTRAINT UK_CANAL_CODIGO UNIQUE (CD_CODIGO),
    CONSTRAINT CK_CANAL_CODIGO CHECK (CD_CODIGO = UPPER(CD_CODIGO) AND LENGTH(TRIM(CD_CODIGO)) > 0)
);
COMMENT ON TABLE TB_CANAL IS 'Canais de atendimento do LarOuAyê (aplicativo web e Telegram).';

CREATE TABLE TB_CIDADAO (
    CD_CIDADAO     NUMBER(10)    NOT NULL,
    NM_CIDADAO     VARCHAR2(80)  NOT NULL,
    DS_EMAIL       VARCHAR2(120),
    CD_CANAL       NUMBER(10)    DEFAULT 1 NOT NULL,
    CD_ID_EXTERNO  VARCHAR2(40),
    DT_CADASTRO    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CIDADAO PRIMARY KEY (CD_CIDADAO),
    CONSTRAINT FK_CIDADAO_CANAL FOREIGN KEY (CD_CANAL) REFERENCES TB_CANAL (CD_CANAL),
    CONSTRAINT UK_CIDADAO_EMAIL UNIQUE (DS_EMAIL),
    CONSTRAINT CK_CIDADAO_EXTERNO CHECK (CD_CANAL = 1 OR CD_ID_EXTERNO IS NOT NULL),
    CONSTRAINT CK_CIDADAO_NOME CHECK (LENGTH(TRIM(NM_CIDADAO)) > 0),
    CONSTRAINT CK_CIDADAO_EMAIL CHECK (DS_EMAIL IS NULL OR (INSTR(DS_EMAIL, '@') > 1 AND INSTR(DS_EMAIL, ' ') = 0))
);
CREATE UNIQUE INDEX UX_CIDADAO_EMAIL_LOWER ON TB_CIDADAO (LOWER(DS_EMAIL));
CREATE UNIQUE INDEX UX_CIDADAO_CANAL_EXTERNO ON TB_CIDADAO (CASE WHEN CD_ID_EXTERNO IS NOT NULL THEN CD_CANAL END, CD_ID_EXTERNO);
COMMENT ON TABLE  TB_CIDADAO IS 'Cidadão que usa o LarOuAyê pelo app web ou pelo Telegram. Só dados mínimos.';
COMMENT ON COLUMN TB_CIDADAO.CD_CANAL IS 'Canal de origem (FK para tb_canal; 1 = WEB, padrão)';
COMMENT ON COLUMN TB_CIDADAO.CD_ID_EXTERNO IS 'Identificador no canal externo (chat_id do Telegram); obrigatório fora do canal WEB';

CREATE TABLE TB_CATEGORIA (
