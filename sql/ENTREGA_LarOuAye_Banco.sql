-- Consulta 1: Quais orientações sobre impostos eu posso ler, em ordem alfabética?
SELECT CD_ORIENTACAO, NM_TITULO, DS_REVISAO
  FROM TB_ORIENTACAO
 WHERE CD_CATEGORIA = (SELECT CD_CATEGORIA FROM TB_CATEGORIA WHERE CD_CODIGO = 'TRIBUTOS')
   AND ST_ATIVO = 1
 ORDER BY NM_TITULO;

-- Consulta 2: Quantas perguntas cada categoria recebeu?
SELECT CA.NM_CATEGORIA, COUNT(*) AS QT_CONSULTAS
  FROM TB_CONSULTA CO
  INNER JOIN TB_CATEGORIA CA ON CA.CD_CATEGORIA = CO.CD_CATEGORIA
 GROUP BY CA.NM_CATEGORIA
 ORDER BY QT_CONSULTAS DESC, CA.NM_CATEGORIA;

-- Consulta 3: Quão confiável é o classificador em cada situação da resposta?
SELECT SC.CD_CODIGO AS DS_STATUS,
       COUNT(CO.VL_CONFIANCA)           AS QT_COM_CONFIANCA,
       ROUND(AVG(CO.VL_CONFIANCA), 2)   AS MEDIA_CONFIANCA,
       MAX(CO.VL_CONFIANCA)             AS MAIOR_CONFIANCA,
       MIN(CO.VL_CONFIANCA)             AS MENOR_CONFIANCA
  FROM TB_CONSULTA CO
  INNER JOIN TB_STATUS_CONSULTA SC ON SC.CD_STATUS = CO.CD_STATUS
 GROUP BY SC.CD_CODIGO
 ORDER BY SC.CD_CODIGO;

-- Consulta 4: Quais categorias são as mais procuradas (mais de 2 perguntas)?
SELECT CA.NM_CATEGORIA, COUNT(*) AS QT_CONSULTAS
  FROM TB_CONSULTA CO
  INNER JOIN TB_CATEGORIA CA ON CA.CD_CATEGORIA = CO.CD_CATEGORIA
 GROUP BY CA.NM_CATEGORIA
HAVING COUNT(*) > 2
 ORDER BY QT_CONSULTAS DESC;

-- Consulta 5: Que respostas o Carlos e a Dona Lúcia receberam no Telegram?
SELECT U.NM_CIDADAO, CO.DS_PERGUNTA, O.NM_TITULO, CO.VL_CONFIANCA
  FROM TB_CONSULTA CO
  INNER JOIN TB_CIDADAO U    ON U.CD_CIDADAO = CO.CD_CIDADAO
  INNER JOIN TB_ORIENTACAO O ON O.CD_ORIENTACAO = CO.CD_ORIENTACAO
  INNER JOIN TB_CANAL CN     ON CN.CD_CANAL = CO.CD_CANAL
 WHERE CN.CD_CODIGO = 'TELEGRAM'
   AND U.NM_CIDADAO IN ('Carlos Mendes', 'Dona Lúcia')
   AND CO.VL_CONFIANCA BETWEEN 0.80 AND 1
   AND CO.DS_PERGUNTA LIKE '%?'
 ORDER BY U.NM_CIDADAO, CO.DT_CONSULTA;

-- Consulta 6: Há orientações que ninguém consultou ainda?
SELECT O.CD_ORIENTACAO, O.NM_TITULO, COUNT(CO.CD_CONSULTA) AS QT_CONSULTAS
  FROM TB_ORIENTACAO O
  LEFT JOIN TB_CONSULTA CO ON CO.CD_ORIENTACAO = O.CD_ORIENTACAO
 GROUP BY O.CD_ORIENTACAO, O.NM_TITULO
 ORDER BY QT_CONSULTAS, O.NM_TITULO;

-- Consulta 7: Em cada etapa da compra, quantas pessoas já concluíram?
SELECT E.NR_ORDEM, E.NM_ETAPA,
       COUNT(CASE WHEN SE.CD_CODIGO = 'CONCLUIDA' THEN 1 END) AS QT_CONCLUIDAS
  FROM TB_CIDADAO_ETAPA UE
  LEFT JOIN TB_STATUS_ETAPA SE ON SE.CD_STATUS = UE.CD_STATUS
  RIGHT JOIN TB_ETAPA E ON E.CD_ETAPA = UE.CD_ETAPA
 GROUP BY E.NR_ORDEM, E.NM_ETAPA
 ORDER BY E.NR_ORDEM;

-- Consulta 8: Quais cidadãos possuem média de confiança superior à média geral das respostas?
SELECT U.NM_CIDADAO, ROUND(AVG(CO.VL_CONFIANCA), 2) AS MEDIA_PESSOAL
  FROM TB_CONSULTA CO
  INNER JOIN TB_CIDADAO U ON U.CD_CIDADAO = CO.CD_CIDADAO
 WHERE CO.VL_CONFIANCA IS NOT NULL
 GROUP BY U.NM_CIDADAO
HAVING AVG(CO.VL_CONFIANCA) > (SELECT AVG(VL_CONFIANCA) FROM TB_CONSULTA)
 ORDER BY MEDIA_PESSOAL DESC, U.NM_CIDADAO;

-- Consulta 9: De onde vêm as perguntas? Quanto cada estado representa?
SELECT SG_UF,
       COUNT(*) AS QT_CONSULTAS,
       ROUND(COUNT(*) * 100 / (SELECT COUNT(*) FROM TB_CONSULTA), 1) AS PC_DO_TOTAL
  FROM TB_CONSULTA
 GROUP BY SG_UF
 ORDER BY QT_CONSULTAS DESC, SG_UF;

-- Consulta 10: Quanto de cada jornada já foi concluído?
SELECT U.NM_CIDADAO,
       SUM(CASE WHEN SE.CD_CODIGO = 'CONCLUIDA' THEN 1 ELSE 0 END) AS ETAPAS_CONCLUIDAS,
       (SELECT COUNT(*) FROM TB_ETAPA) AS ETAPAS_TOTAL,
       ROUND(SUM(CASE WHEN SE.CD_CODIGO = 'CONCLUIDA' THEN 1 ELSE 0 END) * 100 / (SELECT COUNT(*) FROM TB_ETAPA), 0) AS PC_JORNADA
  FROM TB_CIDADAO U
  LEFT JOIN TB_CIDADAO_ETAPA UE ON UE.CD_CIDADAO = U.CD_CIDADAO
  LEFT JOIN TB_STATUS_ETAPA SE  ON SE.CD_STATUS = UE.CD_STATUS
 GROUP BY U.NM_CIDADAO
 ORDER BY PC_JORNADA DESC, U.NM_CIDADAO;

